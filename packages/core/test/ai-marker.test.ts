import { describe, expect, it } from 'vitest';
import {
  AI_ANSWER_COPY_SUFFIX,
  AI_OCR_COPY_SUFFIX,
  AI_OCR_MODEL_COPY_SUFFIX,
  AI_TRANSLATION_COPY_SUFFIX,
  aiGeneratedMarkdownComment,
  exportedMarkdownComment,
  looksLikeAiContent,
  ocrCopySuffix,
  ocrIsAiEngine,
  renderMarkdown,
  withAiExportHeader,
  withAiNoteHeader
} from '@studianda/shared';

/**
 * AI 标识文案的硬约束：
 * - 复制回答/译文/OCR 文本必须自动附带标识；
 * - 导出/存为笔记必须在文件头强制插入声明；
 * - 标识文案不得被“一键去除”的实现绕过（当前不存在开关，测试锁住文件头位置）。
 */
describe('AI 标识文案', () => {
  it('复制回答/译文/OCR 文本都带显式标识且不可去除', () => {
    for (const suffix of [
      AI_ANSWER_COPY_SUFFIX,
      AI_TRANSLATION_COPY_SUFFIX,
      AI_OCR_COPY_SUFFIX
    ]) {
      expect(suffix).toMatch(/AI 生成|机器翻译|OCR\/视觉识别/);
      expect(suffix).toContain('不得删除');
      expect(suffix.startsWith('\n\n')).toBe(true);
    }
    expect(AI_ANSWER_COPY_SUFFIX).toContain('AI 生成内容');
    expect(AI_TRANSLATION_COPY_SUFFIX).toContain('机器翻译');
    expect(AI_OCR_COPY_SUFFIX).toContain('OCR/视觉识别');
  });

  it('存为笔记文件头含 AI 生成提示、学术提示与隐式注释', () => {
    const header = aiGeneratedMarkdownComment();
    expect(header.startsWith('> **AI 生成内容提示**')).toBe(true);
    expect(header).not.toContain('model:');
    expect(header).toContain('> **学术使用提示**');
    expect(header).toContain('<!-- AI-generated by Studianda');
    expect(header).toContain('请回原文核实');
  });

  it('导出文件头含 YAML 隐式标识、声明、学术提示与注释', () => {
    const header = exportedMarkdownComment();
    expect(header.startsWith('---\naigc: true\naigc_generator: Studianda\n')).toBe(true);
    expect(header).toContain('> **AI 生成内容声明**');
    expect(header).toContain('> **学术使用提示**');
    expect(header).toContain('不得删除');
    expect(header).toContain('<!-- Exported by Studianda');
  });

  it('withAiNoteHeader / withAiExportHeader 只前置声明，不改写正文', () => {
    const body = '# 标题\n\n用户正文，保持原样。\n';
    const note = withAiNoteHeader(body);
    expect(note.startsWith('> **AI 生成内容提示**')).toBe(true);
    expect(note.endsWith(body)).toBe(true);

    const exported = withAiExportHeader(body);
    expect(exported.startsWith('---\naigc: true\n')).toBe(true);
    expect(exported).toContain('> **AI 生成内容声明**');
    expect(exported.endsWith(body)).toBe(true);

    // 纯用户内容导出不加任何文件头（由数据层检测 AI 标识后决定）。
    expect(withAiExportHeader(body, false)).toBe(body);
  });

  it('只有 AI 回答/译文/存为笔记/AI 模型识别算 AI 内容', () => {
    expect(looksLikeAiContent(`正文${AI_ANSWER_COPY_SUFFIX}`)).toBe(true);
    expect(looksLikeAiContent(`正文${AI_TRANSLATION_COPY_SUFFIX}`)).toBe(true);
    expect(looksLikeAiContent(aiGeneratedMarkdownComment())).toBe(true);
    expect(looksLikeAiContent(`识别结果${AI_OCR_MODEL_COPY_SUFFIX}`)).toBe(true);
    // 本机 OCR / PDF 文本层不是生成式 AI，不触发 AI 元数据。
    expect(looksLikeAiContent(`识别结果${AI_OCR_COPY_SUFFIX}`)).toBe(false);
    expect(looksLikeAiContent('用户自己写的批注')).toBe(false);
  });

  it('按识别引擎区分本机 OCR 与 AI 模型', () => {
    expect(ocrIsAiEngine('tesseract.js:chi_sim+eng')).toBe(false);
    expect(ocrIsAiEngine('text_layer')).toBe(false);
    expect(ocrIsAiEngine('')).toBe(false);
    for (const engine of ['vision:gpt-4o', 'deepseek_ocr', 'mineru_agent', 'mineru_online', 'custom']) {
      expect(ocrIsAiEngine(engine)).toBe(true);
      expect(ocrCopySuffix(engine)).toContain('AI 模型识别');
    }
    expect(ocrCopySuffix('tesseract.js:chi_sim')).toContain('本机 OCR');
    expect(ocrCopySuffix('text_layer')).not.toContain('AI 模型识别');
  });

  it('导出文件头的 YAML 元数据与隐式注释不会渲染成正文', () => {
    const markdown = withAiExportHeader('# 标题\n\n用户正文。\n');
    const html = renderMarkdown(markdown);
    expect(html).not.toContain('aigc');
    expect(html).not.toContain('Exported by Studianda');
    expect(html).not.toContain('AI-generated by Studianda');
    // 显式提示仍然展示（它是给人看的标识，不是元数据）。
    expect(html).toContain('AI 生成内容声明');
    expect(html).toContain('标题');
  });
});

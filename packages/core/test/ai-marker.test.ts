import { describe, expect, it } from 'vitest';
import {
  AI_ANSWER_COPY_SUFFIX,
  AI_OCR_COPY_SUFFIX,
  AI_TRANSLATION_COPY_SUFFIX,
  aiGeneratedMarkdownComment,
  exportedMarkdownComment,
  withAiExportHeader,
  withAiNoteHeader
} from '@studianda/shared';

/**
 * AI 标识文案的硬约束：
 * - 复制回答/译文/OCR 文本必须自动附带标识；
 * - 导出/存为笔记必须在文件头强制插入声明；
 * - 标识文案不得被“一键去除”的实现绕过（当前不存在开关，测试锁住文件头位置）。
 */
describe('AI 标识文案', () => {
  it('复制回答/译文/OCR 文本都带显式标识且不可去除', () => {
    for (const suffix of [
      AI_ANSWER_COPY_SUFFIX,
      AI_TRANSLATION_COPY_SUFFIX,
      AI_OCR_COPY_SUFFIX
    ]) {
      expect(suffix).toMatch(/AI 生成|机器翻译|机器识别/);
      expect(suffix).toContain('不得删除');
      expect(suffix.startsWith('\n\n')).toBe(true);
    }
    expect(AI_ANSWER_COPY_SUFFIX).toContain('AI 生成内容');
    expect(AI_TRANSLATION_COPY_SUFFIX).toContain('机器翻译');
    expect(AI_OCR_COPY_SUFFIX).toContain('机器识别');
  });

  it('存为笔记文件头含 AI 生成提示与隐式注释', () => {
    const header = aiGeneratedMarkdownComment();
    expect(header.startsWith('> **AI 生成内容提示**')).toBe(true);
    expect(header).not.toContain('model:');
    expect(header).toContain('<!-- AI-generated by Studianda');
    expect(header).toContain('请回原文核实');
  });

  it('导出文件头含 AI 生成声明、学术提示与隐式注释', () => {
    const header = exportedMarkdownComment();
    expect(header.startsWith('> **AI 生成内容声明**')).toBe(true);
    expect(header).toContain('> **学术使用提示**');
    expect(header).toContain('不得删除');
    expect(header).toContain('<!-- Exported by Studianda');
  });

  it('withAiNoteHeader / withAiExportHeader 只前置声明，不改写正文', () => {
    const body = '# 标题\n\n用户正文，保持原样。\n';
    const note = withAiNoteHeader(body);
    expect(note.startsWith('> **AI 生成内容提示**')).toBe(true);
    expect(note.endsWith(body)).toBe(true);

    const exported = withAiExportHeader(body);
    expect(exported.startsWith('> **AI 生成内容声明**')).toBe(true);
    expect(exported.endsWith(body)).toBe(true);
  });
});

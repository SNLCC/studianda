/**
 * AI 生成内容的统一标识文案（复制、存为笔记、导出共用）。
 *
 * 目标：
 * - 复制：在剪贴板文本末尾强制附带标识，避免用户无感知地传播无标识内容；
 * - 导出：在 Markdown 文件头强制写入显式声明 + 学术披露提示 + 隐式注释；
 * - 不提供“一键去除标识”的开关；导出文件可被用户手动编辑，但工具不协助去标识。
 *
 * 说明：这些文案是产品层面的显式标识，不替代 AI 服务提供者的合规义务；
 * 具体标识样式/元数据要求见 docs/USAGE-NOTICE.md 与相关法规。
 */

/** 复制 AI 回答时追加的标识（回答正文之后）。 */
export const AI_ANSWER_COPY_SUFFIX =
  '\n\n（AI 生成内容 · 可能出错，请核实原文；不得删除、篡改或隐匿本标识。）';

/** 复制 AI 译文时追加的标识。 */
export const AI_TRANSLATION_COPY_SUFFIX =
  '\n\n（机器翻译 · 由 AI 生成，可能出错，请核对原文；不得删除、篡改或隐匿本标识。）';

/** 复制 OCR/视觉识别文本时追加的标识。 */
export const AI_OCR_COPY_SUFFIX =
  '\n\n（机器识别 · 可能由 AI 或本机 OCR 生成，可能出错，请核对原图；不得删除、篡改或隐匿本标识。）';

const AI_NOTE_NOTICE =
  '> **AI 生成内容提示**：以下内容由 AI 生成，可能不准确、编造或遗漏；请回原文核实后再引用。';
const AI_EXPORT_NOTICE =
  '> **AI 生成内容声明**：本文件由勘读 Studianda 导出，可能包含 AI 生成的回答、译文、摘要或笔记；AI 生成内容仅供参考，请回原文核实；不得删除、篡改、伪造或隐匿 AI 标识。';
const ACADEMIC_NOTICE =
  '> **学术使用提示**：使用 AI 辅助生成内容时，请按相应机构、期刊或学校的科研诚信要求披露使用范围；作者对最终内容负责。';

/** 存为笔记时的文件头：显式提示 + 隐式注释。 */
export function aiGeneratedMarkdownComment(): string {
  return `${AI_NOTE_NOTICE}\n\n<!-- AI-generated by Studianda; generated-at: ${new Date().toISOString()} -->\n`;
}

/**
 * 导出 Markdown 文件头（笔记/批注导出）。
 *
 * 导出文件里混有用户手写内容与「存为笔记」保存的 AI 回答，因此文件级用显式声明
 * 说明“可能包含 AI 生成内容”并给出学术披露提示；具体某段是否为 AI 生成，
 * 以该段自身的 `AI-generated by Studianda` 内联注释为准。不改写用户正文。
 */
export function exportedMarkdownComment(): string {
  return `${AI_EXPORT_NOTICE}\n\n${ACADEMIC_NOTICE}\n\n<!-- Exported by Studianda; may include AI-generated content (AI-generated sections are marked inline); exported-at: ${new Date().toISOString()} -->\n`;
}

/** 在 Markdown 正文前强制插入「存为笔记」的 AI 生成文件头。 */
export function withAiNoteHeader(markdown: string): string {
  return `${aiGeneratedMarkdownComment()}${markdown}`;
}

/** 在 Markdown 正文前强制插入导出文件的 AI 生成声明。 */
export function withAiExportHeader(markdown: string): string {
  return `${exportedMarkdownComment()}${markdown}`;
}

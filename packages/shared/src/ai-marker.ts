/**
 * AI 生成内容的统一标识文案（复制、存为笔记、导出共用）。
 *
 * 目标：
 * - 复制：在剪贴板文本末尾强制附带标识，避免用户无感知地传播无标识内容；
 * - 导出：在 Markdown 文件头强制写入显式声明 + 学术披露提示 + 隐式注释；
 * - 不提供“一键去除标识”的开关；导出文件可被用户手动编辑，但工具不协助去标识。
 *
 * 说明：这些文案是产品层面的显式标识，不替代 AI 服务提供者的合规义务；
 * 具体标识样式/元数据要求见 docs/USAGE-NOTICE.md 与相关法规。
 */

/** 复制 AI 回答时追加的标识（回答正文之后）。 */
export const AI_ANSWER_COPY_SUFFIX =
  '\n\n（AI 生成内容 · 可能出错，请核实原文；不得删除、篡改或隐匿本标识。）';

/** 复制 AI 译文时追加的标识。 */
export const AI_TRANSLATION_COPY_SUFFIX =
  '\n\n（机器翻译 · 由 AI 生成，可能出错，请核对原文；不得删除、篡改或隐匿本标识。）';

/** 复制本机 OCR（Tesseract / PDF 文本层）文本时追加的标识：不属于 AI 生成。 */
export const AI_OCR_COPY_SUFFIX =
  '\n\n（OCR/视觉识别 · 本机 OCR，可能出错，请核对原图；不得删除、篡改或隐匿本标识。）';

/** 复制 AI 模型识别（视觉模型 / DeepSeek OCR / MinerU / 自定义解析）文本时追加的标识。 */
export const AI_OCR_MODEL_COPY_SUFFIX =
  '\n\n（OCR/视觉识别 · AI 模型识别，可能出错，请核对原图；不得删除、篡改或隐匿本标识。）';

/**
 * OCR/视觉识别的来源是否属于 AI 模型。
 *
 * `tesseract.js:*` 是本机 OCR，`text_layer` 是 PDF 自带文本层；其余
 * （`vision:<model>`、`deepseek_ocr`、`mineru_*`、`custom`）都按 AI/模型解析处理。
 */
export function ocrIsAiEngine(engine: string | null | undefined): boolean {
  const value = (engine ?? '').trim().toLowerCase();
  if (!value) return false;
  return !(value.startsWith('tesseract') || value === 'text_layer');
}

/** 按识别引擎选择复制标识；未知引擎按本机处理，不误标 AI。 */
export function ocrCopySuffix(engine: string | null | undefined): string {
  return ocrIsAiEngine(engine) ? AI_OCR_MODEL_COPY_SUFFIX : AI_OCR_COPY_SUFFIX;
}

/** 界面上的来源说明（不含"可能出错"等提示语，供小字标签复用）。 */
export function ocrSourceLabel(engine: string | null | undefined): string {
  return ocrIsAiEngine(engine) ? 'AI 模型' : '本机 OCR';
}

const AI_NOTE_NOTICE =
  '> **AI 生成内容提示**：以下内容由 AI 生成，可能不准确、编造或遗漏；请回原文核实后再引用。';
const AI_EXPORT_NOTICE =
  '> **AI 生成内容声明**：本文件由勘读 Studianda 导出，可能包含 AI 生成的回答、译文、摘要或笔记；AI 生成内容仅供参考，请回原文核实；不得删除、篡改、伪造或隐匿 AI 标识。';
const ACADEMIC_NOTICE =
  '> **学术使用提示**：使用 AI 辅助生成内容时，请按相应机构、期刊或学校的科研诚信要求披露使用范围；作者对最终内容负责。';

/**
 * 判断一段文本是否带"AI 生成内容"的标识。
 *
 * 认四类：复制 AI 回答的后缀（「AI 生成内容」）、复制译文的后缀（「机器翻译 · 由 AI 生成」）、
 * 复制 AI 模型识别文本的后缀（「AI 模型识别」）、存为笔记与导出的 `<!-- AI-generated by Studianda`。
 * 本机 Tesseract 与 PDF 文本层的复制标识不带这些字样，因此不会被当成生成式 AI 内容。
 */
export const AI_CONTENT_MARKER_RE = /AI 生成内容|机器翻译 · 由 AI 生成|AI 模型识别|AI-generated by Studianda/;

export function looksLikeAiContent(text: string | null | undefined): boolean {
  return typeof text === 'string' && AI_CONTENT_MARKER_RE.test(text);
}

/** 存为笔记时的文件头：显式提示 + 学术披露提示 + 隐式注释。 */
export function aiGeneratedMarkdownComment(): string {
  return `${AI_NOTE_NOTICE}\n\n${ACADEMIC_NOTICE}\n\n<!-- AI-generated by Studianda; generated-at: ${new Date().toISOString()} -->\n`;
}

/**
 * 导出 Markdown 文件头（笔记/批注导出）。
 *
 * 导出文件里混有用户手写内容与「存为笔记」保存的 AI 回答，因此文件级用显式声明
 * 说明“可能包含 AI 生成内容”并给出学术披露提示；具体某段是否为 AI 生成，
 * 以该段自身的 `AI-generated by Studianda` 内联注释为准。不改写用户正文。
 *
 * 文件头最前面是 YAML frontmatter，作为**隐式标识**（机器可读的元数据字段），
 * 比纯 HTML 注释更接近《人工智能生成合成内容标识办法》对元数据的要求；
 * 渲染时 `renderMarkdown` 会跳过 frontmatter 与这些注释，不显示成正文。
 */
export function exportedMarkdownComment(): string {
  const exportedAt = new Date().toISOString();
  const frontmatter = [
    '---',
    'aigc: true',
    'aigc_generator: Studianda',
    `aigc_exported_at: ${exportedAt}`,
    '---',
    ''
  ].join('\n');
  return `${frontmatter}\n\n${AI_EXPORT_NOTICE}\n\n${ACADEMIC_NOTICE}\n\n<!-- Exported by Studianda; may include AI-generated content (AI-generated sections are marked inline); exported-at: ${exportedAt} -->\n`;
}

/** 在 Markdown 正文前强制插入「存为笔记」的 AI 生成文件头。 */
export function withAiNoteHeader(markdown: string): string {
  return `${aiGeneratedMarkdownComment()}${markdown}`;
}

/**
 * 在 Markdown 正文前插入导出文件头；`containsAi` 为 false 时不加（纯用户内容的导出件）。
 *
 * 默认 true 是为了兼容仍按"总是加标识"调用的宿主；数据层的 `store.exportMarkdown()`
 * 会先检测笔记/批注里是否真的带 AI 标识，再决定是否写入。
 */
export function withAiExportHeader(markdown: string, containsAi = true): string {
  return containsAi ? `${exportedMarkdownComment()}${markdown}` : markdown;
}
